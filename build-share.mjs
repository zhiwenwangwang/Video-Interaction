import { readFile,writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve,basename } from 'node:path';
const root=fileURLToPath(new URL('.',import.meta.url));
const read=path=>readFile(resolve(root,path),'utf8');
const bytes=async path=>(await readFile(resolve(root,path))).toString('base64');

// All source modules use named imports/exports. Wrap each in its own scope,
// keeping their dependency graph and private names intact in a classic script.
const rig=JSON.parse(await read('assets/rig.json'));
await writeFile(resolve(root,'rig-data.js'),`export const RIG=${JSON.stringify(rig)};\n`);
const modules=new Map();
function id(path){return '__shadow_module_'+basename(path,'.js').replaceAll('-','_');}
async function bundle(path){
  if(modules.has(path))return;
  let code=await read(path);const imports=[];
  const pattern=/^import\s*\{([^}]+)\}\s*from\s*['"]\.\/([^'"]+)['"];?\s*$/gm;
  for(const match of code.matchAll(pattern)){
    await bundle(match[2]);imports.push(`const {${match[1]}}=${id(match[2])};`);
  }
  code=code.replace(pattern,'');const exports=[];
  code=code.replace(/^export\s+(?:(async)\s+)?(const|let|class|function)\s+([\w$]+)/gm,(_,async,kind,name)=>{
    exports.push(name);return `${async?'async ':''}${kind} ${name}`;
  });
  if(/^\s*(import|export)\s/m.test(code)||code.includes('import.meta'))throw new Error(`Unsupported module syntax in ${path}`);
  modules.set(path,`const ${id(path)}=(()=>{\n${imports.join('\n')}\n${code}\nreturn {${exports.join(',')}};\n})();\n`);
}
await bundle('app.js');
await writeFile(resolve(root,'browser-bundle.js'),`// Generated by build-share.mjs; edit the source modules and rebuild.\n(()=>{'use strict';\n${[...modules.values()].join('\n')}\n})();\n`);

const pack={
  worker:await read('hand-worker.js'),vision:await read('vendor/vision_bundle.mjs'),
  simd:{loader:await read('vendor/wasm/vision_wasm_internal.js'),wasm:await bytes('vendor/wasm/vision_wasm_internal.wasm')},
  noSimd:{loader:await read('vendor/wasm/vision_wasm_nosimd_internal.js'),wasm:await bytes('vendor/wasm/vision_wasm_nosimd_internal.wasm')},
  model:await bytes('vendor/hand_landmarker.task'),
};
await writeFile(resolve(root,'camera-data.js'),`// MediaPipe offline runtime; lazy-loaded only when starting the camera.\nwindow.__SHADOW_CAMERA_PACK=${JSON.stringify(pack)};\n`);
console.log(`Built ${modules.size} source modules and the offline hand runtime.`);
